#!/usr/bin/env node
// Split a rendered overlay into the files the server-side dry-run needs:
//
//   namespaces.yaml       Namespace objects (applied for real, harmless)
//   priorityclasses.yaml  PriorityClass objects (cluster-scoped, applied for real)
//   rest.yaml             everything else (server dry-run)
//
// ResourceQuota admission is evaluated at Pod creation, not at Deployment
// creation, so this split exists only to make the dry-run's API/admission
// checks meaningful; it does not validate quota capacity. Capacity is checked
// by scripts/k8s/quota-report.mjs.
//
//   node scripts/k8s/split-render.mjs dist/k8s/production.yaml dist/k8s/production

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';

const inputPath = process.argv[2];
const outDir = process.argv[3];

if (!inputPath || !outDir) {
  console.error('usage: node scripts/k8s/split-render.mjs <rendered.yaml> <output-dir>');
  process.exit(2);
}

const raw = readFileSync(inputPath, 'utf8').replace(/\r\n/g, '\n');

// Split on document separators that start a line. Manifests generated by
// kustomize never contain a bare `---` inside a block scalar at column 0.
const docs = raw
  .split(/^---\s*$/m)
  .map((doc) => doc.replace(/^\s*\n/, '').trim())
  .filter(Boolean);

function kindOf(doc) {
  const match = doc.match(/^kind:\s*([^\s]+)\s*$/m);
  return match ? match[1] : '';
}

const namespaces = docs.filter((doc) => kindOf(doc) === 'Namespace');
const priorityClasses = docs.filter((doc) => kindOf(doc) === 'PriorityClass');
const rest = docs.filter((doc) => !['Namespace', 'PriorityClass'].includes(kindOf(doc)));

mkdirSync(outDir, { recursive: true });

const write = (name, parts) => {
  const path = join(outDir, name);
  writeFileSync(path, parts.map((part) => `---\n${part}\n`).join(''), 'utf8');
  console.log(`wrote ${path} (${parts.length} objects)`);
};

write('namespaces.yaml', namespaces);
write('priorityclasses.yaml', priorityClasses);
write('rest.yaml', rest);

console.log(
  `split ${basename(inputPath)}: ${namespaces.length} Namespace, ` +
    `${priorityClasses.length} PriorityClass, ${rest.length} other`,
);
